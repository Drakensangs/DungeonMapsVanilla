-- Marker format:
--	 { "name", x, y, floor, "atlasKey", atlasBossIndex, "comment" }
--
-- name
--	 Literal string, or a prefixed ID for auto-localization:
--		n<id>  NPC		 e.g. "n11502"  > Ragnaros
--		o<id>  Object	 e.g. "o177964" > Fathom Stone
--		q<id>  Quest	 e.g. "q4867"   > [60] Urok Doomhowl
--		i<id>  Item		 e.g. "i9425"   > [Pendulum of Doom]
--	 Prefix types below may be combined in any order before the name:
--		E		 Hides the marker if Atlas isn't detected.
--		Marker type:
--		  !		 Use a quest marker instead of the boss marker.
--		  L		 Use a loot marker instead of the boss marker.
--		  O		 Use an object marker instead of the boss marker.
--		Faction:
--		  A		 Alliance only markers (hidden by the filter for Horde).
--		  H		 Horde only markers (hidden by the filter for Alliance).
--	 Examples: "!n7850"  "A Lo19284"  "!H n9020"
--
-- floor
--	 Floor number or table of indices for markers shared across floors:
--	 e.g. {1, 2, 3}
--
-- atlasBossIndex
--	 Index into the AtlasLoot boss list for the given atlasKey.
--	 Use 0 if there is no AtlasLoot entry.
--	 Can be a table of indices for a random encounter pool; a random
--	 number is picked each time the marker is clicked.
--
-- comment  (optional)
--	 Shown in the marker tooltip below the boss name.
--	 Use |n to insert a line break.
--	 Accepts NPC, Object, Quest & Item IDs. Item names are color coded
--	 based on their rarity. Updates automatically once cached.
--	 Prefix a segment with !A or !H to show it only to that faction,
--	 e.g. "!A Ends q4362.|n!H Ends q4003."
--
-- Markers can be calibrated in-game with /dmv calib; new coordinates are saved
